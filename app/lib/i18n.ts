export function translate(lang: Lang, text: string, vars?: Record<string, string | number>): string {
  let s = lang === "id" ? ID[text] ?? text : text;
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m));
  return s;
}
